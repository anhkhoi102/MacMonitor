import Darwin

/// Tiny wrapper around `sysctlbyname`, the kernel's key/value interface for
/// hardware facts (CPU model, core counts, RAM size…).
/// Try it in Terminal: `sysctl machdep.cpu.brand_string hw.perflevel0.logicalcpu`
enum Sysctl {
    static func string(_ name: String) -> String? {
        var size = 0
        // First call asks how many bytes are needed, second call reads them.
        guard sysctlbyname(name, nil, &size, nil, 0) == 0, size > 0 else { return nil }
        var buffer = [UInt8](repeating: 0, count: size)
        guard sysctlbyname(name, &buffer, &size, nil, 0) == 0 else { return nil }
        return String(decoding: buffer.prefix { $0 != 0 }, as: UTF8.self)
    }

    static func int(_ name: String) -> Int? {
        var value: Int32 = 0
        var size = MemoryLayout<Int32>.size
        guard sysctlbyname(name, &value, &size, nil, 0) == 0 else { return nil }
        return Int(value)
    }

    static func uint64(_ name: String) -> UInt64? {
        var value: UInt64 = 0
        var size = MemoryLayout<UInt64>.size
        guard sysctlbyname(name, &value, &size, nil, 0) == 0 else { return nil }
        return value
    }
}
